-- Run this in your Supabase SQL Editor.
create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  phone text,
  attending boolean not null default true,
  guest_count integer not null default 1,
  message text
);

alter table public.rsvps enable row level security;
-- Allows visitors to submit RSVPs. Do not expose service-role keys in the website.
create policy "Anyone can submit an RSVP"
on public.rsvps for insert
to anon
with check (char_length(name) > 0 and guest_count between 1 and 10);

-- Create a public storage bucket for shared guest photos.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('wedding-photos', 'wedding-photos', true, 10485760, array['image/jpeg','image/png','image/webp','image/heic'])
on conflict (id) do nothing;

create policy "Anyone can upload wedding photos"
on storage.objects for insert
to anon
with check (bucket_id = 'wedding-photos');
